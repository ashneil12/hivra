import PublicSite from "@/components/public-site/PublicSite";
import { Breadcrumbs, EditorialArt, EditorialQuestions, EditorialRelated } from "@/components/public-editorial/Editorial";
import ActionLinks from "@/components/public-editorial/ActionLinks";
import ArticleNavigation from "@/components/public-editorial/ArticleNavigation.client";
import styles from "../../../components/public-editorial/secondary-site.module.css";
import agentStyles from "../agents.module.css";
import type { Metadata } from "next";
import { notFound } from "next/navigation";
import StructuredData from "@/components/StructuredData";
import { buildAbsoluteTitleMetadata } from "@/lib/metadata";
import { SITE_URL } from "@/lib/seo-urls";
import {
  AGENT_OFFER_PRICE_USD,
  AGENT_SEO_ENTRIES,
  agentDeployHref,
  agentPageTitle,
  getAgentSeoEntry,
} from "@/lib/hivra/agent-seo-catalog";
import { getAgent } from "@/lib/hivra/agent-catalog";
import { HeadingLines, Inline } from "../AgentProse";
import { AgentSectionView } from "../AgentBlocks";
import { getAgentPageContent } from "../content";
import { resolveLinks } from "../content/links";
import { plainText, slugifyHeading } from "../content/markup";

interface AgentPageParams {
  params: Promise<{ slug: string }>;
}

// Only the catalog's slugs exist; anything else is a real 404.
export const dynamicParams = false;

export function generateStaticParams() {
  return AGENT_SEO_ENTRIES.map((entry) => ({ slug: entry.slug }));
}

export async function generateMetadata({ params }: AgentPageParams): Promise<Metadata> {
  const { slug } = await params;
  const entry = getAgentSeoEntry(slug);
  const agent = entry ? getAgent(entry.slug) : undefined;
  if (!entry || !agent) return {};

  // The browser title is the finished title, brand included (Ash's, bar the three run-level titles reworded on
  // 2026-10-21), so it is published as an absolute title and the root layout does not add " | Hivra" a second time.
  return buildAbsoluteTitleMetadata({
    path: `/agents/${entry.slug}`,
    title: agentPageTitle(entry),
    description: entry.metaDescription,
    // Generated by app/agents/[slug]/opengraph-image.tsx.
    images: [
      {
        url: `/agents/${entry.slug}/opengraph-image`,
        width: 1200,
        height: 630,
        alt: `${agent.name} on Hivra`,
        type: "image/png",
      },
    ],
  });
}

export default async function AgentPage({ params }: AgentPageParams) {
  const { slug } = await params;
  const entry = getAgentSeoEntry(slug);
  const agent = entry ? getAgent(entry.slug) : undefined;
  const content = entry ? getAgentPageContent(entry.slug) : undefined;
  if (!entry || !agent || !content) notFound();

  const pageUrl = `${SITE_URL}/agents/${entry.slug}`;
  const deployHref = agentDeployHref(entry);
  const position = AGENT_SEO_ENTRIES.findIndex((other) => other.slug === entry.slug) + 1;

  const schema = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "SoftwareApplication",
        name: `${agent.name} on Hivra`,
        applicationCategory: "DeveloperApplication",
        operatingSystem: "Web",
        description: entry.metaDescription,
        url: pageUrl,
        // The price is monthly, so the Offer says so. There is deliberately no
        // aggregateRating or review: Hivra publishes none, and inventing one is
        // worse than these pages not qualifying for Software App rich results.
        offers: {
          "@type": "Offer",
          price: AGENT_OFFER_PRICE_USD,
          priceCurrency: "USD",
          priceSpecification: {
            "@type": "UnitPriceSpecification",
            price: AGENT_OFFER_PRICE_USD,
            priceCurrency: "USD",
            unitText: "MONTH",
            billingDuration: "P1M",
          },
          url: `${SITE_URL}${deployHref}`,
        },
      },
      {
        "@type": "BreadcrumbList",
        itemListElement: [
          { "@type": "ListItem", position: 1, name: "Home", item: SITE_URL },
          { "@type": "ListItem", position: 2, name: "Agents", item: `${SITE_URL}/agents` },
          { "@type": "ListItem", position: 3, name: agent.name, item: pageUrl },
        ],
      },
      {
        // The same words the reader sees: the answers are the page's own strings without their markup.
        "@type": "FAQPage",
        mainEntity: content.faqs.map(({ q, a }) => ({
          "@type": "Question",
          name: q,
          acceptedAnswer: { "@type": "Answer", text: plainText(a) },
        })),
      },
    ],
  };

  const contents = [
    ...content.sections.map(({ heading }) => ({ id: slugifyHeading(heading), label: heading })),
    { id: "common-questions", label: "Common questions" },
  ];
  const questions = content.faqs.map(({ q, a }) => ({
    q,
    a: plainText(a),
    node: (
      <p>
        <Inline text={a} />
      </p>
    ),
  }));
  const relatedLinks = content.related.slugs.flatMap((relatedSlug) => {
    const related = getAgent(relatedSlug);
    return related ? [{ label: related.name, href: `/agents/${relatedSlug}` }] : [];
  });

  return (
    <PublicSite className={styles.page} data-page="agent-detail">
      <StructuredData schema={schema} />
      <main className={styles.main} id="main-content">
        <Breadcrumbs items={[{ label: "Agents", href: "/agents" }, { label: agent.name }]} />
        <header className={styles.articleHeader}>
          <div>
            <h1>
              <HeadingLines text={content.h1} />
            </h1>
            <div className={agentStyles.lead}>
              {content.lead.map((paragraph) => (
                <p key={paragraph}>
                  <Inline text={paragraph} />
                </p>
              ))}
            </div>
            <ActionLinks items={resolveLinks(content.heroLinks, entry, "agent-hero")} />
          </div>
          <EditorialArt number={String(position).padStart(2, "0")} label={agent.name} />
        </header>
        <div className={styles.articleLayout}>
          <ArticleNavigation items={contents} />
          <div className={`${styles.articleBody} ${agentStyles.body}`}>
            {content.sections.map((section) => (
              <AgentSectionView key={section.heading} section={section} />
            ))}
            <div id="common-questions" className={agentStyles.faq}>
              <EditorialQuestions questions={questions} />
            </div>
          </div>
        </div>
        <section className={agentStyles.closing}>
          <h2>
            <HeadingLines text={content.closing.heading} />
          </h2>
          <ActionLinks items={resolveLinks(content.closing.links, entry, "agent-closing")} />
        </section>
        <p className={agentStyles.note}>{content.affiliation}</p>
        <div className={agentStyles.related}>
          <EditorialRelated title={content.related.heading} links={relatedLinks} />
        </div>
      </main>
    </PublicSite>
  );
}
