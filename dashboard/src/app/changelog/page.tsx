import type { Metadata } from "next";
import Link from "next/link";
import { ArrowUpRight, Link as LinkIcon } from "lucide-react";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";

import PublicSite from "@/components/public-site/PublicSite";
import { ActionLinks } from "@/components/public-editorial/ActionLinks";
import { Breadcrumbs, EditorialMarkdownLink } from "@/components/public-editorial/Editorial";
import styles from "../../components/public-editorial/secondary-site.module.css";
import StructuredData from "@/components/StructuredData";
import { absoluteTitle, buildWebsiteMetadata } from "@/lib/metadata";
import { OG_IMAGE } from "@/lib/og-meta";
import { SITE_URL } from "@/lib/seo-urls";
import { getTokenSurfaceView, tokenSurfacesVisible } from "@/lib/compliance/token-surface-view";
import { readChangelog, resolveChangelogEntries, type ChangelogEntry } from "@/lib/changelog";
import { CHANGELOG_FEED_TITLE } from "@/lib/changelog-rss";
import { PUBLIC_START_HREF } from "@/lib/public-start";
import local from "./changelog.module.css";
import { CHANGELOG_COPY } from "./changelog-content";

const CHANGELOG_URL = `${SITE_URL}/changelog`;
const CHANGELOG_FEED_URL = `${CHANGELOG_URL}/rss.xml`;
const TITLE = "Hivra Changelog | Product Updates and Fixes";
const DESCRIPTION =
  "Read what has changed on Hivra, from agent memory and browser sessions to reliability improvements and dashboard updates.";

const websiteMetadata = buildWebsiteMetadata({
  path: "/changelog",
  title: TITLE,
  description: DESCRIPTION,
  // Branded dynamic OG card generated by app/changelog/opengraph-image.tsx (#public-og-images).
  images: [OG_IMAGE.changelog],
});

export const metadata: Metadata = {
  title: absoluteTitle(TITLE),
  description: DESCRIPTION,
  ...websiteMetadata,
  // Preserve the canonical from buildWebsiteMetadata, add RSS auto-discovery so
  // feed readers and browsers find /changelog/rss.xml from the page head.
  alternates: {
    ...websiteMetadata.alternates,
    types: {
      "application/rss+xml": [{ url: CHANGELOG_FEED_URL, title: CHANGELOG_FEED_TITLE }],
    },
  },
};

function formatDate(iso: string): string {
  const d = new Date(`${iso}T00:00:00Z`);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toLocaleDateString("en-GB", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  });
}

function EntryBlock({ entry }: { entry: ChangelogEntry }) {
  return (
    <article id={entry.date} className={`${styles.changeEntry} ${local.entry}`}>
      <header>
        <a href={`#${entry.date}`} aria-label={`Permalink to ${entry.date} entry`} className={styles.eyebrow}>
          <LinkIcon size={13} aria-hidden="true" />
          <time dateTime={entry.date}>{formatDate(entry.date)}</time>
        </a>
        <h2>{entry.title}</h2>
      </header>
      <div className={styles.articleBody}>
        <ReactMarkdown
          remarkPlugins={[remarkGfm]}
          components={{
            a: ({ node, ...props }) => {
              void node;
              return <EditorialMarkdownLink {...props} />;
            },
          }}
        >
          {entry.body}
        </ReactMarkdown>
      </div>
    </article>
  );
}

// The notes are the same for everyone except the section that names the Bankr wallet, which shows
// only while the token surfaces are on and the viewer is not in a listed country. With the switch
// off, or no country listed, nothing reads the request and the page stays static.
export default async function ChangelogPage() {
  const view = await getTokenSurfaceView();
  const { lastUpdated, entries: shipped } = readChangelog();
  const entries = resolveChangelogEntries(shipped, tokenSurfacesVisible(view));
  const { masthead, list } = CHANGELOG_COPY;

  const schema = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "BreadcrumbList",
        itemListElement: [
          { "@type": "ListItem", position: 1, name: "Home", item: SITE_URL },
          { "@type": "ListItem", position: 2, name: "Changelog", item: CHANGELOG_URL },
        ],
      },
      {
        "@type": "WebPage",
        "@id": `${CHANGELOG_URL}#webpage`,
        url: CHANGELOG_URL,
        name: TITLE,
        description: DESCRIPTION,
        isPartOf: { "@id": `${SITE_URL}/#website` },
        ...(lastUpdated ? { dateModified: lastUpdated } : {}),
      },
    ],
  };

  return (
    <PublicSite className={styles.page} data-page="changelog">
      <StructuredData schema={schema} />
      <main className={`${styles.main} ${local.end}`} id="main-content">
        <Breadcrumbs items={[{ label: "Changelog" }]} />
        <header className={`${styles.masthead} ${local.masthead}`}>
          <h1>{masthead.heading}</h1>
          {masthead.paragraphs.map((paragraph) => (
            <p key={paragraph}>{paragraph}</p>
          ))}
          <ActionLinks
            items={[
              { label: "Explore agents", href: "/agents", kind: "primary" },
              { label: "See the roadmap", href: "/roadmap", kind: "secondary" },
            ]}
          />
        </header>
        <section className={local.listHead} aria-labelledby="changelog-shipped">
          <header>
            <span className={styles.eyebrow}>{list.eyebrow}</span>
            <h2 id="changelog-shipped">{list.heading}</h2>
          </header>
          <div>
            <p className={local.lede}>
              {list.lede}
              {entries.length > 0 ? ` ${list.coverage(formatDate(entries[0].date))}` : ""}
            </p>
            {lastUpdated ? (
              <p className={`${styles.metadata} ${local.listMeta}`}>
                {list.lastUpdated} <time dateTime={lastUpdated}>{formatDate(lastUpdated)}</time>
              </p>
            ) : null}
            <div className={`${styles.changeLinks} ${local.links}`}>
              <Link href="/week">
                This week <ArrowUpRight size={17} aria-hidden="true" />
              </Link>
              <Link href="/roadmap">
                Roadmap <ArrowUpRight size={17} aria-hidden="true" />
              </Link>
              <a href="/changelog/rss.xml">
                RSS feed <ArrowUpRight size={17} aria-hidden="true" />
              </a>
              <Link href={PUBLIC_START_HREF}>
                Deploy Now <ArrowUpRight size={17} aria-hidden="true" />
              </Link>
            </div>
          </div>
        </section>
        {entries.length > 0 ? entries.map((entry) => <EntryBlock key={entry.date} entry={entry} />) : <p>No changelog entries yet.</p>}
      </main>
    </PublicSite>
  );
}
