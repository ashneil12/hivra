/**
 * Behavioral contract for the env-file shell-injection fix:
 *
 *  - values in the conservative safe charset stay byte-identical (unquoted) so
 *    platform-generated tokens, hex keys, URLs and model names produce exactly
 *    the historical output ad-hoc sed/grep readers depend on;
 *  - anything else is single-quoted, which bash treats as fully literal — so a
 *    hostile `$(...)`/backtick payload in a user-controlled value cannot execute
 *    when host scripts `set -a; . .env; set +a` the file — while python-dotenv
 *    and Docker Compose strip the quotes back to the literal value;
 *  - shapes no cross-reader encoding exists for (apostrophe + shell-active
 *    chars, trailing backslash) are refused instead of written corruptly.
 */

describe("serializeEnvValue", () => {
  it("keeps safe-charset values byte-identical (unquoted)", () => {
    for (const value of [
      "",
      "true",
      "0.0.0.0",
      "8642",
      "sk-or-v1-abc123",
      "https://api.openai.com/v1",
      "https://llm.example.com/v1/api-version,2024-01-01",
      "anthropic/claude-opus-4.1",
      "hven_live_9f8e7d6c5b",
      "/home/hermes/.hermes/bin:/usr/local/bin",
      "deepseek-v3.2",
    ]) {
      expect(serializeEnvValue(value)).toBe(value);
    }
  });

  it("single-quotes values carrying shell-active characters", () => {
    expect(serializeEnvValue("https://x/$(touch /tmp/pwned)/v1")).toBe(
      "'https://x/$(touch /tmp/pwned)/v1'"
    );
    expect(serializeEnvValue("back`tick`")).toBe("'back`tick`'");
    expect(serializeEnvValue("semi;colon")).toBe("'semi;colon'");
    expect(serializeEnvValue("with space")).toBe("'with space'");
    expect(serializeEnvValue("dollar${HOME}x")).toBe("'dollar${HOME}x'");
    expect(serializeEnvValue("has?glob")).toBe("'has?glob'");
    expect(serializeEnvValue("hash#frag")).toBe("'hash#frag'");
    expect(serializeEnvValue('double"quote')).toBe(`'double"quote'`);
    expect(serializeEnvValue("tilde~home")).toBe("'tilde~home'");
  });

  it("strips line breaks and NUL bytes before quoting (SEC-04 contract)", () => {
    // Line break removal can drop a value back into the safe charset.
    expect(serializeEnvValue("abcd\n")).toBe("abcd");
    expect(serializeEnvValue("sk-real\nINJECTED=1")).toBe("sk-realINJECTED=1");
    expect(serializeEnvValue("tv\0INJECTED=1")).toBe("tvINJECTED=1");
  });

  it("double-quotes apostrophe-only values (no shell-active chars present)", () => {
    expect(serializeEnvValue("it's a name")).toBe('"it\'s a name"');
    expect(serializeEnvValue("Ash's helper")).toBe('"Ash\'s helper"');
  });

  it("refuses values no faithful cross-reader encoding exists for", () => {
    for (const value of [
      "it's $(evil)", // apostrophe + command substitution
      "it's `evil`", // apostrophe + backticks
      "it's \"quoted\"", // apostrophe + double quote
      "it's a\\path", // apostrophe + backslash
      "endswith\\", // trailing backslash: python-dotenv swallows the rest of the file
    ]) {
      expect(() => serializeEnvValue(value, "TEST_KEY")).toThrow(/Refusing to write TEST_KEY/);
    }
  });
});

describe("serializeEnvAssignmentLine", () => {
  it("passes comments and blank lines through verbatim", () => {
    expect(serializeEnvAssignmentLine("# Generated by Hermes Deploy")).toBe(
      "# Generated by Hermes Deploy"
    );
    expect(serializeEnvAssignmentLine("")).toBe("");
  });

  it("re-serializes only the value part, splitting at the first =", () => {
    expect(serializeEnvAssignmentLine("API_SERVER_KEY=abc123")).toBe("API_SERVER_KEY=abc123");
    expect(serializeEnvAssignmentLine("OPENAI_BASE_URL=https://x/$(id)/v1")).toBe(
      "OPENAI_BASE_URL='https://x/$(id)/v1'"
    );
    // `=` inside the value belongs to the value.
    expect(serializeEnvAssignmentLine("KEY=a=b=c")).toBe("KEY=a=b=c");
    expect(serializeEnvAssignmentLine("KEY=a b=c")).toBe("KEY='a b=c'");
  });
});

/**
 * Behavioral proof: source generated env content in bash and assert no command
 * execution plus literal round-trip. This mirrors exactly what the box does in
 * the profile-gateway launch script and gateway supervisor.
 */
function bashSourceAndRead(envContent: string, keys: string[]): Record<string, string> {
  const dir = mkdtempSync(join(tmpdir(), "envlines-"));
  try {
    const envPath = join(dir, ".env");
    writeFileSync(envPath, envContent, "utf8");
    const probe = [
      `set -a`,
      `. "${envPath}"`,
      `set +a`,
      ...keys.map((k) => `printf '%s\\x00%s\\x00' '${k}' "$${k}"`),
    ].join("\n");
    const out = execFileSync("bash", ["-c", probe], { encoding: "utf8" });
    const parts = out.split("\x00");
    const result: Record<string, string> = {};
    for (let i = 0; i + 1 < parts.length; i += 2) {
      result[parts[i]] = parts[i + 1];
    }
    return result;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

describe("bash-source behavior of serialized env files", () => {
  it("does not execute command substitution in a hostile base URL", () => {
    const marker = join(mkdtempSync(join(tmpdir(), "envpwn-")), "pwned");
    // buildProviderEnv deliberately returns raw KEY=value pairs (other callers
    // split them into patch dicts); serialization happens at the file-writing
    // boundary inside buildHermesEnvLines.
    const lines = buildHermesEnvLines({
      containerName: "agent-x",
      apiServerKey: "x".repeat(64),
      provider: "venice",
      apiKey: "sk-test",
      model: "m",
      agentSettings: {
        maxIterations: 60,
        toolProgressMode: "all",
        compressionThreshold: 0.85,
        sessionResetMode: "both",
        customLlmBaseUrl: `https://x/$(touch ${marker})/v1`,
      },
    });
    const envContent = lines.join("\n") + "\n";
    const read = bashSourceAndRead(envContent, ["OPENAI_BASE_URL", "OPENAI_API_KEY"]);

    expect(existsSync(marker)).toBe(false);
    expect(read.OPENAI_BASE_URL).toBe(`https://x/$(touch ${marker})/v1`);
    expect(read.OPENAI_API_KEY).toBe("sk-test");
  });

  it("does not execute backticks or splat a semi-colon payload into a second command", () => {
    const marker = join(mkdtempSync(join(tmpdir(), "envpwn-")), "pwned");
    const envContent =
      serializeEnvAssignmentLine(`OPENAI_BASE_URL=https://x/\`touch ${marker}\`/v1`) +
      "\n" +
      serializeEnvAssignmentLine(`TAVILY_API_KEY=tv;touch ${marker}`) +
      "\n";
    const read = bashSourceAndRead(envContent, ["OPENAI_BASE_URL", "TAVILY_API_KEY"]);

    expect(existsSync(marker)).toBe(false);
    expect(read.OPENAI_BASE_URL).toBe(`https://x/\`touch ${marker}\`/v1`);
    expect(read.TAVILY_API_KEY).toBe(`tv;touch ${marker}`);
  });

  it("round-trips spaces, dollar signs and apostrophe display names literally", () => {
    const envContent = [
      serializeEnvAssignmentLine("HERMES_WEBUI_BOT_NAME=Ash's helper"),
      serializeEnvAssignmentLine("MEM0_USER_ID=user id with spaces"),
      serializeEnvAssignmentLine("RETAINDB_PROJECT=price is $5"),
    ].join("\n") + "\n";
    const read = bashSourceAndRead(envContent, [
      "HERMES_WEBUI_BOT_NAME",
      "MEM0_USER_ID",
      "RETAINDB_PROJECT",
    ]);

    expect(read.HERMES_WEBUI_BOT_NAME).toBe("Ash's helper");
    expect(read.MEM0_USER_ID).toBe("user id with spaces");
    expect(read.RETAINDB_PROJECT).toBe("price is $5");
  });

  it("keeps platform values byte-identical end-to-end", () => {
    const lines = buildHermesEnvLines({
      containerName: "agent-x",
      apiServerKey: "a".repeat(64),
      provider: "openai",
      apiKey: "sk-proj-abc123",
      model: "gpt-5.4",
      agentSettings: {
        maxIterations: 60,
        toolProgressMode: "all",
        compressionThreshold: 0.85,
        sessionResetMode: "both",
      },
    });
    // Every line stays unquoted for this all-safe-charset input, except the
    // platform's literal `*` CORS wildcard — glob chars are outside the safe
    // charset by deliberate conservatism, and every reader strips the quotes.
    for (const line of lines) {
      if (line.startsWith("API_SERVER_CORS_ORIGINS=")) {
        expect(line).toBe("API_SERVER_CORS_ORIGINS='*'");
        continue;
      }
      expect(line).not.toMatch(/='/);
      expect(line).not.toMatch(/="/);
    }
    const read = bashSourceAndRead(lines.join("\n") + "\n", [
      "API_SERVER_KEY",
      "OPENAI_API_KEY",
      "HERMES_MODEL",
      "OPENAI_BASE_URL",
    ]);
    expect(read.API_SERVER_KEY).toBe("a".repeat(64));
    expect(read.OPENAI_API_KEY).toBe("sk-proj-abc123");
    expect(read.HERMES_MODEL).toBe("gpt-5.4");
    expect(read.OPENAI_BASE_URL).toBe("https://api.openai.com/v1");
  });
});

describe("builder output: hostile values become inert in generated env files", () => {
  it("buildHermesEnvLines quotes a hostile customLlmBaseUrl instead of emitting it raw", () => {
    const lines = buildHermesEnvLines({
      containerName: "agent-x",
      apiServerKey: "x".repeat(64),
      provider: "venice",
      apiKey: "sk-test",
      model: "m",
      agentSettings: {
        maxIterations: 60,
        toolProgressMode: "all",
        compressionThreshold: 0.85,
        sessionResetMode: "both",
        customLlmBaseUrl: "https://evil.example/$(touch /tmp/pwned)/v1",
      },
    });

    const baseUrlLine = lines.find((line) => line.startsWith("OPENAI_BASE_URL="));
    expect(baseUrlLine).toBe(
      "OPENAI_BASE_URL='https://evil.example/$(touch /tmp/pwned)/v1'"
    );
    const envContent = lines.join("\n") + "\n";
    const read = bashSourceAndRead(envContent, ["OPENAI_BASE_URL"]);
    expect(read.OPENAI_BASE_URL).toBe("https://evil.example/$(touch /tmp/pwned)/v1");
  });

  it("buildHermesEnvLines quotes hostile memory-system endpoints and user ids", () => {
    const lines = buildHermesEnvLines({
      containerName: "agent-x",
      apiServerKey: "x".repeat(64),
      provider: "openai",
      apiKey: "sk-test",
      model: "gpt-5.4",
      memorySystem: {
        provider: "mem0",
        mem0ApiKey: "m0-$(touch /tmp/pwned)",
        mem0UserId: "user; rm -rf /",
      } as never,
    });

    expect(lines).toContain("MEM0_API_KEY='m0-$(touch /tmp/pwned)'");
    expect(lines).toContain("MEM0_USER_ID='user; rm -rf /'");
    const read = bashSourceAndRead(lines.join("\n") + "\n", ["MEM0_API_KEY", "MEM0_USER_ID"]);
    expect(read.MEM0_API_KEY).toBe("m0-$(touch /tmp/pwned)");
    expect(read.MEM0_USER_ID).toBe("user; rm -rf /");
  });

  it("throws rather than write a value with no faithful encoding", () => {
    expect(() =>
      buildHermesEnvLines({
        containerName: "agent-x",
        apiServerKey: "x".repeat(64),
        provider: "openai",
        apiKey: "sk-test",
        model: "gpt-5.4",
        agentSettings: {
          maxIterations: 60,
          toolProgressMode: "all",
          compressionThreshold: 0.85,
          sessionResetMode: "both",
          tavilyApiKey: "tv-ending-in\\",
        },
      })
    ).toThrow(/Refusing to write TAVILY_API_KEY/);
  });
});

const webuiBaseParams: WebUIDeployParams = {
  instanceId: "inst-env-lines",
  containerName: "agent-inst-env-lines",
  fqdn: "agent.example.com",
  cpuLimit: 2,
  ramLimit: 4096,
  llmApiKey: "provider-key",
  inferenceProvider: "custom",
  defaultModel: "deepseek-v3.2",
  baseUrl: "https://crof.ai/v1",
  webuiPassword: "webui-password",
};

describe("WebUI lane env builders shell-quote hostile values", () => {
  it("buildHermesEnvFile single-quotes a hostile base URL", () => {
    const envFile = buildHermesEnvFile({
      ...webuiBaseParams,
      baseUrl: "https://evil.example/$(touch /tmp/pwned)/v1",
    });
    expect(envFile).toContain(
      "OPENAI_BASE_URL='https://evil.example/$(touch /tmp/pwned)/v1'"
    );
    const read = bashSourceAndRead(envFile, ["OPENAI_BASE_URL", "OPENAI_API_KEY"]);
    expect(read.OPENAI_BASE_URL).toBe("https://evil.example/$(touch /tmp/pwned)/v1");
    expect(read.OPENAI_API_KEY).toBe("provider-key");
  });

  it("buildWebUIComposeEnv single-quotes a hostile bot name and base URL", () => {
    const composeEnv = buildWebUIComposeEnv({
      ...webuiBaseParams,
      agentName: "helper $(touch /tmp/pwned)",
      baseUrl: "https://evil.example/$(touch /tmp/pwned)/v1",
    });
    expect(composeEnv).toContain("HERMES_WEBUI_BOT_NAME='helper $(touch /tmp/pwned)'");
    expect(composeEnv).toContain(
      "OPENAI_BASE_URL='https://evil.example/$(touch /tmp/pwned)/v1'"
    );
    const read = bashSourceAndRead(composeEnv, ["HERMES_WEBUI_BOT_NAME", "OPENAI_BASE_URL"]);
    expect(read.HERMES_WEBUI_BOT_NAME).toBe("helper $(touch /tmp/pwned)");
    expect(read.OPENAI_BASE_URL).toBe("https://evil.example/$(touch /tmp/pwned)/v1");
  });

  it("keeps a normal deploy byte-clean: no quotes anywhere for safe values", () => {
    const envFile = buildHermesEnvFile(webuiBaseParams);
    const lines = envFile.split("\n").filter((line) => /^[A-Za-z_][A-Za-z0-9_]*=/.test(line));
    for (const line of lines) {
      expect(line).not.toMatch(/='/);
    }
    expect(envFile).toContain("OPENAI_BASE_URL=https://crof.ai/v1");
    expect(envFile).toContain("OPENAI_API_KEY=provider-key");
  });

  it("round-trips an apostrophe bot name through bash sourcing", () => {
    const composeEnv = buildWebUIComposeEnv({
      ...webuiBaseParams,
      agentName: "Ash's helper",
    });
    expect(composeEnv).toContain('HERMES_WEBUI_BOT_NAME="Ash\'s helper"');
    const read = bashSourceAndRead(composeEnv, ["HERMES_WEBUI_BOT_NAME"]);
    expect(read.HERMES_WEBUI_BOT_NAME).toBe("Ash's helper");
  });
});

describe("python-dotenv parity (skipped when python-dotenv is not importable)", () => {
  it("single-quoted and double-quoted forms parse back to literal values", () => {
    // The in-container agent reads these files with python-dotenv, so the
    // quoted forms bash treats as literal must parse back to the same literal
    // there too — otherwise quoting would corrupt the value the agent sees.
    let dotenvAvailable = true;
    try {
      execFileSync("python3", ["-c", "import dotenv"]);
    } catch {
      dotenvAvailable = false;
    }
    if (!dotenvAvailable) {
      console.warn("python-dotenv not importable — skipping parity check");
      return;
    }

    const dir = mkdtempSync(join(tmpdir(), "envpy-"));
    try {
      const envPath = join(dir, ".env");
      const content = [
        serializeEnvAssignmentLine("A=plain-value"),
        serializeEnvAssignmentLine("C=with space"),
        serializeEnvAssignmentLine("D=it's apostrophe"),
        serializeEnvAssignmentLine("E=semi;pipe|amp&"),
      ].join("\n") + "\n";
      writeFileSync(envPath, content, "utf8");

      const pyScript = `
import sys
from dotenv import dotenv_values
parsed = dotenv_values(${JSON.stringify(envPath)})
for key in ("A", "C", "D", "E"):
    sys.stdout.write(key + "\\x00" + (parsed.get(key) or "") + "\\x00")
`;
      const out = execFileSync("python3", ["-c", pyScript], { encoding: "utf8" });
      const parts = out.split("\x00");
      const parsed: Record<string, string> = {};
      for (let i = 0; i + 1 < parts.length; i += 2) parsed[parts[i]] = parts[i + 1];

      expect(parsed.A).toBe("plain-value");
      expect(parsed.C).toBe("with space");
      expect(parsed.D).toBe("it's apostrophe");
      expect(parsed.E).toBe("semi;pipe|amp&");
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});
