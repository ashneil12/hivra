#!/usr/bin/env node
// Rewrites src/lib/tools/agent-tools/openrouter-snapshot.ts from OpenRouter's public model list
// (https://openrouter.ai/api/v1/models, no key needed). Run it, review the diff, commit it.
// Only models that accept tool calls and return text are kept, because an agent needs tool calls.
// The allowlist below is the editorial choice; free models that support tools are always included.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ALLOW = [
  "anthropic/claude-opus-5.5", "anthropic/claude-sonnet-5.5", "anthropic/claude-haiku-5.5",
  "openai/gpt-6.1-sol", "openai/gpt-6.1-terra", "openai/gpt-6-luna", "openai/gpt-oss-120b", "openai/gpt-oss-20b",
  "google/gemini-3.8-flash", "google/gemini-4-carbon", "google/gemma-4-31b-it",
  "x-ai/grok-4.7",
  "z-ai/glm-5.3", "z-ai/glm-5.3-flash",
  "deepseek/deepseek-v4-flash", "deepseek/deepseek-v4-pro",
  "moonshotai/kimi-k2.7-code", "moonshotai/kimi-k3.1-pro",
  "minimax/minimax-m3", "minimax/minimax-m3.1-flash",
  "qwen/qwen3.8-flash", "qwen/qwen3.7-plus", "qwen/qwen3-coder-next", "qwen/qwen3.8-27b",
  "mistralai/mistral-large-4-0", "mistralai/devstral-2512", "mistralai/mistral-small-2603",
  "meta-llama/llama-4-maverick",
  "nvidia/nemotron-3-super-120b-a12b", "nvidia/nemotron-3-ultra-550b-a55b",
  "xiaomi/mimo-v2.6-flash", "xiaomi/mimo-v2.6-pro",
  "stepfun/step-3.5-flash", "tencent/hy4",
];

const res = await fetch("https://openrouter.ai/api/v1/models");
if (!res.ok) throw new Error(`OpenRouter returned ${res.status}`);
const { data } = await res.json();
const today = process.env.SNAPSHOT_DATE ?? new Date().toISOString().slice(0, 10);

const keep = data.filter((m) => {
  const toolCalls = (m.supported_parameters ?? []).includes("tools");
  const textOut = JSON.stringify(m.architecture?.output_modalities) === '["text"]';
  const prompt = Number(m.pricing?.prompt);
  const free = prompt === 0 && Number(m.pricing?.completion) === 0;
  const expiresSoon = m.expiration_date && new Date(m.expiration_date) < new Date(Date.now() + 45 * 864e5);
  if (!toolCalls || !textOut || expiresSoon || m.id.startsWith("~") || m.id.startsWith("liquid/") || m.id.startsWith("dots-studio/") || m.id.includes(":batch") || prompt < 0) return false;
  return ALLOW.includes(m.id) || (free && m.id !== "openrouter/free");
});

const rows = keep
  .map((m) => ({
    id: m.id,
    name: m.name.replace(/\s*\(free\)\s*$/i, ""),
    provider: m.id.split("/")[0],
    inputUsdPerM: Math.round(Number(m.pricing.prompt) * 1e8) / 100,
    outputUsdPerM: Math.round(Number(m.pricing.completion) * 1e8) / 100,
    contextTokens: m.context_length,
    free: Number(m.pricing.prompt) === 0 && Number(m.pricing.completion) === 0,
    reasoning: Boolean(m.reasoning) || (m.supported_parameters ?? []).includes("reasoning"),
    imageInput: (m.architecture?.input_modalities ?? []).includes("image"),
  }))
  .sort((a, b) => a.id.localeCompare(b.id));

const missing = ALLOW.filter((id) => !rows.some((r) => r.id === id));
if (missing.length) console.warn("Not in the OpenRouter list or filtered out:", missing.join(", "));

const out = `// GENERATED by scripts/refresh-agent-model-snapshot.mjs from https://openrouter.ai/api/v1/models.
// Do not edit by hand. Prices are USD per million tokens at OpenRouter's list price, before any
// provider discount or credit fee. Models listed here accept tool calls and return text.

export interface OpenRouterModelRow {
  id: string;
  name: string;
  provider: string;
  inputUsdPerM: number;
  outputUsdPerM: number;
  contextTokens: number;
  free: boolean;
  reasoning: boolean;
  imageInput: boolean;
}

export const OPENROUTER_SNAPSHOT_DATE = ${JSON.stringify(today)};
export const OPENROUTER_SOURCE_URL = "https://openrouter.ai/models";

export const OPENROUTER_MODELS: readonly OpenRouterModelRow[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(fileURLToPath(new URL("../src/lib/tools/agent-tools/openrouter-snapshot.ts", import.meta.url)), out);
console.log(`Wrote ${rows.length} models`);
