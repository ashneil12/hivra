#!/usr/bin/env node
// Embeds provisioner/hermes-plugins/hivra-inbox into a TypeScript module so the
// install sweep can copy it onto Hermes computers without reading files at run
// time. Run after changing the plugin: node scripts/generate-inbox-plugin-bundle.cjs
// (a test fails while the embedded copy and the files differ).
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const dir = path.join(root, "provisioner", "hermes-plugins", "hivra-inbox");
const names = ["plugin.yaml", "__init__.py"];
const askHook = path.join(root, "provisioner", "agent-addons", "hivra-ask-claude", "hivra-ask-hook.py");

function askBundle() {
  const body = fs.readFileSync(askHook);
  return { file: body.toString("base64"), version: crypto.createHash("sha256").update(body).digest("hex").slice(0, 16) };
}

function bundle() {
  const files = {};
  const hash = crypto.createHash("sha256");
  for (const name of names) {
    const body = fs.readFileSync(path.join(dir, name));
    files[name] = body.toString("base64");
    hash.update(name).update("\0").update(body).update("\0");
  }
  return { files, version: hash.digest("hex").slice(0, 16) };
}

function render({ files, version }) {
  const lines = Object.entries(files).map(([name, b64]) => `  ${JSON.stringify(name)}: ${JSON.stringify(b64)},`);
  const ask = askBundle();
  return `// Auto-generated by scripts/generate-inbox-plugin-bundle.cjs from
// provisioner/hermes-plugins/hivra-inbox and provisioner/agent-addons/hivra-ask-claude.
// Do not edit by hand.

export const INBOX_PLUGIN_VERSION = ${JSON.stringify(version)};

/** File name -> base64 contents. */
export const INBOX_PLUGIN_FILES: Readonly<Record<string, string>> = {
${lines.join("\n")}
};

/** Claude Code's "Ask me first" hook (base64) and its version. */
export const ASK_HOOK_VERSION = ${JSON.stringify(ask.version)};
export const ASK_HOOK_FILE = ${JSON.stringify(ask.file)};
`;
}

module.exports = { bundle, askBundle, render };

if (require.main === module) {
  const out = path.join(root, "src", "lib", "agent-inbox", "plugin-bundle.generated.ts");
  fs.writeFileSync(out, render(bundle()));
  console.log(`wrote ${path.relative(root, out)}`);
}
